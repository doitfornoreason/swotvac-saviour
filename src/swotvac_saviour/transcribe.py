CropFn = Callable[[str, int, str, str | None], bytes]
# call(messages, model, key) -> assistant text; injectable for tests.
ModelCall = Callable[[list[dict], str, str], str]


class TranscriptionError(ValueError):
    """The LLM path failed guard rails after the allowed retries."""


def parse_env_file(path: Path) -> dict[str, str]:
    """Minimal dotenv parser: KEY=VALUE lines, comments and blanks ignored."""
    values: dict[str, str] = {}
    try:
        text = path.read_text(encoding="utf8")
    except OSError:
        return values
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        values[key.strip()] = value.strip().strip("'\"")
    return values


def load_api_key(study_dir: str | Path | None = None) -> str | None:
    """OpenRouter key from .env files (study dir, then repo root), then env.

    The .env value always wins over an ambient environment variable.
    """
    candidates: list[Path] = []
    if study_dir:
        candidates.append(Path(study_dir) / ".env")
    candidates.append(Path(__file__).resolve().parents[2] / ".env")
    for path in candidates:
        key = parse_env_file(path).get("OPENROUTER_API_KEY")
        if key:
            return key
    return os.environ.get("OPENROUTER_API_KEY")


# --- guard rails ---------------------------------------------------------------

_HTML_RE = re.compile(r"</?[a-zA-Z][^>]*>")


def balanced_braces(text: str) -> bool:
    depth = 0
    for c in text:
        if c == "{":
            depth += 1
        elif c == "}" and (depth := depth - 1) < 0:
            return False
    return depth == 0


def check_transcription(
    result: dict[str, Any], expected_label: str
) -> list[str]:
    """Structural guard rails for one LLM result. Empty list = pass."""
    problems: list[str] = []
    label = str(result.get("label", "")).strip()
    if label != expected_label:
        problems.append(f"label mismatch: got {label!r}, expected {expected_label!r}")
    body = str(result.get("body", "")).strip()
    if not body:
        problems.append("empty body")
    if _HTML_RE.search(body):
        problems.append("raw HTML in body")
    body_latex = str(result.get("body_latex", "")).strip()
    if not body_latex:
        problems.append("empty body_latex")
    elif not balanced_braces(body_latex):
        problems.append("unbalanced braces in body_latex")
    if _HTML_RE.search(body_latex):
        problems.append("raw HTML in body_latex")
    try:
        float(result.get("confidence"))
    except (TypeError, ValueError):
        problems.append("missing or non-numeric confidence")
    return problems


# --- model call -----------------------------------------------------------------

def openrouter_call(messages: list[dict], model: str, key: str) -> str:
    """One chat completion via OpenRouter. Raises RuntimeError on transport/API errors."""
    import httpx  # lazy: keep startup cheap when the LLM engine is unused

    response = httpx.post(
        API_URL,
        headers={"Authorization": f"Bearer {key}"},
        json={"model": model, "messages": messages},
        timeout=120,
    )
    if response.status_code != 200:
        raise RuntimeError(
            f"OpenRouter {response.status_code}: {response.text[:300]}"
        )
    payload = response.json()
    try:
        return payload["choices"][0]["message"]["content"]
    except (KeyError, IndexError, TypeError) as err:
        raise RuntimeError(f"unexpected OpenRouter response: {payload}") from err


def _extract_json(text: str) -> dict[str, Any]:
    """Parse the model's JSON object, tolerating code fences and prose."""
    stripped = text.strip()
    fence = re.search(r"```(?:json)?\s*(.*?)```", stripped, re.DOTALL)
    if fence:
        stripped = fence.group(1).strip()
    start = stripped.find("{")
    end = stripped.rfind("}")
    if start == -1 or end == -1:
        raise ValueError(f"no JSON object in model response: {text[:200]}")
    return json.loads(stripped[start : end + 1])


PROMPT = """You are transcribing one mathematics question from a rendered PDF crop.
Return ONLY a JSON object with exactly these keys:
- "label": the question label, exactly "{label}"
- "body": the full question text as plain text, including ALL sub-parts (a), (b), ...
- "body_latex": the same text as KaTeX-safe LaTeX: plain prose may stay plain,
  math written with LaTeX commands (e.g. \\frac{{a}}{{b}}, \\sum_{{i=1}}^n), no
  HTML, no $ delimiters, balanced braces
- "confidence": a number from 0 to 1 estimating transcription fidelity
Rules: transcribe faithfully, never solve the question, never add hints,
never paraphrase or omit sub-parts. If the crop is cut off, transcribe what is
visible and lower confidence."""


def transcribe_question(
    label: str,
    crop_png: bytes,
    *,
    model: str,
    key: str,
    call: ModelCall = openrouter_call,
    retries: int = 1,
) -> dict[str, Any]:
    """Transcribe one question crop. Returns {label, body, body_latex, confidence}.

    Raises TranscriptionError when guard rails still fail after ``retries``.
    """
    data_url = "data:image/png;base64," + base64.b64encode(crop_png).decode("ascii")
    messages: list[dict] = [
        {
            "role": "user",
            "content": [
                {"type": "text", "text": PROMPT.format(label=label)},
                {"type": "image_url", "image_url": {"url": data_url}},
            ],
        }
    ]
    problems: list[str] = []
    for attempt in range(retries + 1):
        if problems:
            messages = messages[:1] + [
                {
                    "role": "user",
                    "content": (
                        "Your previous answer failed these checks: "
                        + "; ".join(problems)
                        + ". Fix them and return the JSON object again."
                    ),
                }
            ]
        text = call(messages, model, key)
        try:
            result = _extract_json(text)
        except (ValueError, json.JSONDecodeError) as err:
            problems = [f"unparseable JSON: {err}"]
            continue
        problems = check_transcription(result, label)
        if not problems:
            return {
                "label": str(result["label"]).strip(),
                "body": str(result["body"]).strip(),
                "body_latex": str(result["body_latex"]).strip(),
                "confidence": float(result["confidence"]),
            }
    raise TranscriptionError("; ".join(problems))


# --- crop rendering --------------------------------------------------------------

def crop_png_bytes(
    pdf_path: str, page_number: int, start_label: str, end_label: str | None,
    dpi: int = 150,
) -> bytes:
    """PNG of the region from ``start_label`` to the next label (or page end).

    Falls back to the full page when either label is not found by text search
    (scanned PDFs without a text layer).
    """
    import pymupdf  # lazy

    doc = pymupdf.open(pdf_path)
    try:
        page = doc[page_number - 1]
        starts = page.search_for(start_label)
        if not starts:
            return page.get_pixmap(dpi=dpi).tobytes("png")
        top = starts[0].y0 - 4
        bottom = page.rect.y1
        if end_label:
            ends = page.search_for(end_label)
            if ends:
                bottom = ends[0].y0 - 4
        clip = pymupdf.Rect(0, top, page.rect.x1, max(bottom, top + 10))
        return page.get_pixmap(dpi=dpi, clip=clip).tobytes("png")
    finally:
        doc.close()
