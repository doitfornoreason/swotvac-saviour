"""LLM transcription of question crops via OpenRouter (OpenAI-compatible).

The LLM reads a rendered crop of one question and returns structured JSON. The
deterministic parser (parser.py) still runs first: its labels seed the request
and its output is the fallback when the LLM path fails. Hints are never
generated by the LLM - they come only from verbatim ``[Hint: ...]`` text found
by the deterministic parser.
"""

from __future__ import annotations

import base64
import json
import os
import re
import sqlite3
from pathlib import Path
from typing import Any, Callable

from . import normalise

API_URL = "https://openrouter.ai/api/v1/chat/completions"
# Cheap vision-capable default; overridable per sync from the web UI.
